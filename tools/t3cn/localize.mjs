const TRANSLATABLE_FIELDS = "label|title|placeholder|accessibilityLabel|accessibilityHint|description|detail|message|header|subtitle|actionLabel|buttonLabel|confirmLabel|cancelLabel|emptyTitle|emptyMessage";
const attr = new RegExp("(\\b(?:" + TRANSLATABLE_FIELDS + ")\\s*=\\s*)([\"'])([^\"'\\r\\n]+)\\2", "g");
const expr = new RegExp("(\\b(?:" + TRANSLATABLE_FIELDS + ")\\s*=\\s*\\{\\s*)([\"'])([^\"'\\r\\n]+)\\2(\\s*\\})", "g");
const obj = new RegExp("(\\b(?:" + TRANSLATABLE_FIELDS + ")\\s*:\\s*)([\"'])([^\"'\\r\\n]+)\\2", "g");
const literalText = />([ \t]*)([A-Za-z][^<>{}\r\n]*?)([ \t]*)</g;
const dialogTitle = /(\b(?:Dialog|Alert)\.alert\(\s*)(["'])([^"'\r\n]+)\2/g;
const trans = (value) => Object.hasOwn(dictionary, value) ? dictionary[value] : value;

let changed = 0;
let translated = 0;
function visit(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (entry.name === "__tests__" || entry.name === "generated" || entry.name === "fixtures") continue;
      visit(join(dir, entry.name));
      continue;
    }
    if (!entry.name.endsWith(".tsx") || /\.(?:test|spec)\.tsx$/.test(entry.name)) continue;
    const path = join(dir, entry.name);
    let src = readFileSync(path, "utf8");
    const original = src;
    const swap = (value) => {
      const translatedValue = trans(value);
      if (translatedValue !== value) translated++;
      return translatedValue;
    };
    src = src.replace(attr, (all, prefix, quote, value) => prefix + quote + swap(value) + quote);
    src = src.replace(expr, (all, prefix, quote, value, suffix) => prefix + quote + swap(value) + quote + suffix);
    src = src.replace(obj, (all, prefix, quote, value) => prefix + quote + swap(value) + quote);
    src = src.replace(literalText, (all, leading, value, trailing) => ">" + leading + swap(value) + trailing + "<");
    src = src.replace(dialogTitle, (all, prefix, quote, value) => prefix + quote + swap(value) + quote);
    if (src !== original) {
      writeFileSync(path, src);
      changed++;
    }
  }
}
visit(root);
